use super::{
    FreshnessFragmentId, FreshnessHistoryGeneration, FreshnessMemoryId, HISTORICAL_POLICY_DIGEST,
    SEMANTIC_POLICY_DIGEST,
};

#[test]
fn identity_values_preserve_bytes_and_order() {
    let bytes = [0xa5; 32];
    let generation = [0x5a; 16];
    assert_eq!(FreshnessMemoryId(bytes).0, bytes);
    assert_eq!(FreshnessFragmentId(bytes).0, bytes);
    assert_eq!(FreshnessHistoryGeneration(generation).0, generation);
    assert!(FreshnessMemoryId([0; 32]) < FreshnessMemoryId(bytes));
}

